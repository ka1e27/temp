// FNV-1a over a string. Used for configHash on the battle<->meta seam so the
// meta layer can verify an outcome corresponds to the config it issued.
// PURE.

/** @param {string} str @returns {string} 8-char hex digest */
export function fnv1a(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

/**
 * Stable stringify — object keys sorted recursively, so two structurally equal
 * configs hash identically regardless of key insertion order.
 */
export function stableStringify(value) {
  if (value === null || typeof value !== 'object') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  const keys = Object.keys(value).sort();
  return `{${keys.map((k) => `${JSON.stringify(k)}:${stableStringify(value[k])}`).join(',')}}`;
}
